const KEY = "mapmylan_lang";

function initial(): Lang {
  const saved = localStorage.getItem(KEY);
  if (saved === "fr" || saved === "en") return saved;
  // Le français est la langue par défaut du produit : sans choix enregistré
  // on reste en français, quelle que soit la langue du navigateur.
  return "fr";
}

let current: Lang = initial();
const listeners = new Set<() => void>();

export function getLang(): Lang { return current; }

export function setLang(l: Lang) {
  current = l;
  localStorage.setItem(KEY, l);
  document.documentElement.lang = l;
  listeners.forEach(fn => fn());
}

function subscribe(fn: () => void) {
  listeners.add(fn);
  return () => { listeners.delete(fn); };
}

export function translate(key: string, vars?: Record<string, string | number>): string {
  const out = DICT[current][key] ?? DICT.en[key] ?? key;
  if (!vars) return out;
  return out.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

// Hook : re-rend le composant au changement de langue.
export function useT() {
  useSyncExternalStore(subscribe, getLang, getLang);
  return translate;
}

export function useLang(): [Lang, (l: Lang) => void] {
  const l = useSyncExternalStore(subscribe, getLang, getLang);
  return [l, setLang];
}
